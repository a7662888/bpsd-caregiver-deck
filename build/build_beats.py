"""narration.json + audio durations -> beats.js consumed by deck.js.

Also prepares the chapter-pill avatar (阿嬤 face cropped from the bath illustration) and copies
the Noto Sans TC variable font into vendor/ so the deck works offline.

  py -3 -X utf8 build/build_beats.py
"""
import json, os, shutil, subprocess
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def dur(path):
    return round(float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                                       "-of", "csv=p=0", path], capture_output=True, text=True).stdout), 3)


def main():
    lines = json.load(open(os.path.join(ROOT, "build", "narration.json"), encoding="utf-8"))
    beats = [{"id": l["id"], "slide": l["slide"], "step": l["step"], "text": l["text"],
              "src": f"audio/tts/{l['id']}.mp3", "dur": dur(os.path.join(ROOT, "audio", "tts", l["id"] + ".mp3"))}
             for l in lines]
    with open(os.path.join(ROOT, "beats.js"), "w", encoding="utf-8") as f:
        f.write("// generated by build/build_beats.py — do not edit\nwindow.BEATS = ")
        json.dump(beats, f, ensure_ascii=False, indent=0)
        f.write(";\n")
    print(f"beats.js: {len(beats)} beats, {sum(b['dur'] for b in beats):.1f}s narration")

    av = os.path.join(ROOT, "assets", "avatar.png")
    if not os.path.exists(av):
        im = Image.open(os.path.join(ROOT, "assets", "s3_bath.png")).convert("RGB")
        face = im.crop((1010, 70, 1250, 310)).resize((192, 192), Image.LANCZOS)
        mask = Image.new("L", (192, 192), 0)
        ImageDraw.Draw(mask).ellipse((0, 0, 191, 191), fill=255)
        out = Image.new("RGBA", (192, 192)); out.paste(face, (0, 0), mask); out.save(av)
        print("avatar.png written")

    vend = os.path.join(ROOT, "vendor")
    os.makedirs(vend, exist_ok=True)
    font = os.path.join(vend, "NotoSansTC-VF.ttf")
    if not os.path.exists(font):
        shutil.copy(r"C:\Windows\Fonts\NotoSansTC-VF.ttf", font)
        print("font vendored")


if __name__ == "__main__":
    main()
